"""Task 5 experiments.

A) generation model: every model from llm.MODELS writes the 10 methods, store = gpt-5-mini summaries
B) summary model: chunk descriptions (Task 3) generated by every model -> separate stores;
   retrieval quality on the 10 tasks + end-to-end with fixed generation model(s)

Each configuration is repeated REPEATS times (gpt-5 models ignore temperature -> non-deterministic).
Writes results/summary.json and prints markdown tables. Leaves the repository in original state.

    python run_experiments.py [--repeats 3] [--only A|B] [--b-gen-models gpt-5-mini gpt-5.4-nano]
"""
from __future__ import annotations

import argparse
import json
import re
import statistics as st

from embed_chunks import SUMMARY_MODEL, build_store, store_paths
from llm import MODELS
from retrieve import search
from solve_tasks import RESULTS, load_tasks, reset, run, task_text


def mean_sd(xs: list[float]) -> str:
    return f"{st.mean(xs):.1f} ± {st.stdev(xs):.1f}" if len(xs) > 1 else f"{xs[0]:.1f}"


def summarize_runs(runs: list[dict]) -> dict:
    per_task: dict[str, int] = {}
    for r in runs:
        for a in r["answers"]:
            per_task[a["task"]] = per_task.get(a["task"], 0) + int(a["solved"])
    return {
        "tasks_solved": [r["tasks_solved"] for r in runs],
        "tests_passed": [r["tests"]["passed"] for r in runs],
        "task_tests_passed": [sum(a["tests_passed"] for a in r["answers"]) for r in runs],
        "broken_outside": [len(r["broken_outside_task_tests"]) for r in runs],
        "write_errors": [sum(not a["written"] for a in r["answers"]) for r in runs],
        "completion_tokens": [r["completion_tokens"] for r in runs],
        "seconds_per_task": [st.mean(a["seconds"] for a in r["answers"]) for r in runs],
        "per_task_solved": per_task,
    }


def retrieval_quality(summary_model: str) -> dict:
    store = store_paths(summary_model)[1]
    ranks, test_hits = [], 0
    for t in load_tasks():
        res = search(task_text(t), 95, store)
        for i, (c, _) in enumerate(res):
            if c["file"] == t["file"] and f"def {t['method']}(" in c["text"] and (
                    c["class_name"] == t["class"] or re.search(rf"class {t['class']}\b", c["text"])):
                ranks.append(i + 1)
                break
        test_hits += any("/tests/" in c["file"] and t["class"] in c["text"] for c, _ in res[:5])
    return {"gold_ranks": ranks, "r1": sum(r == 1 for r in ranks) / len(ranks),
            "r5": sum(r <= 5 for r in ranks) / len(ranks), "mrr": st.mean(1 / r for r in ranks),
            "class_tests_in_top5": test_hits}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repeats", type=int, default=3)
    ap.add_argument("--only", choices=["A", "B"])
    ap.add_argument("--b-gen-models", nargs="+", default=["gpt-5-mini"])
    args = ap.parse_args()
    summary_path = RESULTS / "summary.json"
    summary = json.loads(summary_path.read_text()) if summary_path.exists() else {"A": {}, "B": {}}

    if args.only in (None, "A"):
        print("== A: generation model (summaries by gpt-5-mini)")
        for gen in MODELS:
            runs = [run(gen, SUMMARY_MODEL, f"A{i}") for i in range(args.repeats)]
            summary["A"][gen] = summarize_runs(runs)
            summary_path.write_text(json.dumps(summary, indent=2))

    if args.only in (None, "B"):
        print("== B: summary model")
        for sm in MODELS:
            build_store(sm)
            entry = summary["B"].setdefault(sm, {})
            entry["retrieval"] = retrieval_quality(sm)
            print(f"   {sm}: retrieval {entry['retrieval']}")
            for gen in args.b_gen_models:
                runs = [run(gen, sm, f"B{i}") for i in range(args.repeats)]
                entry[gen] = summarize_runs(runs)
            summary_path.write_text(json.dumps(summary, indent=2))

    reset()
    print("\n| gen model | tasks solved /10 | task tests passed /70 | all tests passed /481 | broken outside | write errors | s/task |")
    print("|---|---|---|---|---|---|---|")
    for gen, s in summary["A"].items():
        print(f"| {gen} | {mean_sd(s['tasks_solved'])} | {mean_sd(s['task_tests_passed'])} | "
              f"{mean_sd(s['tests_passed'])} | {sum(s['broken_outside'])} | {sum(s['write_errors'])} | "
              f"{st.mean(s['seconds_per_task']):.1f} |")


if __name__ == "__main__":
    main()
